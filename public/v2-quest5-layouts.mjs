export const Q5_ROOMS = Object.freeze(Object.fromEntries(Object.entries(authored).map(([id, plan]) => {
  const spawnPositions = plan.guards.map(([square]) => [Number(square.slice(1)) - 1, square.charCodeAt(0) - 65]);
  const foes = plan.guards.map(([, faces, role]) => ({faces, role: role === 'boss' ? 'normal' : role, variant: role === 'boss' ? 'boss' : 'normal'}));
  const scenery = plan.pieces.map(([asset, x, y, w, h]) => {
    const cells = [];
    for (let row = y; row < y + h; row++) for (let col = x; col < x + w; col++) {
      if (plan.rows[row][col] === '#') cells.push([col, row]);
    }
    return {asset, x, y, w, h, cells};
  });
  return [id, {rows: plan.rows, spawnPositions, foes, scenery}];
})));
